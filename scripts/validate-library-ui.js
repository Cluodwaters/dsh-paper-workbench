async (page) => {
  await page.locator('[data-view="all"]').click();
  const checks=[];
  const stamp='[第二阶段界面验收 '+Date.now().toString(36)+']';
  const check=(name,ok,details)=>{checks.push({name,passed:Boolean(ok),details});if(!ok)throw new Error(name+': '+JSON.stringify(details));};
  const request=async(path,body)=>page.evaluate(async({path,body})=>{const r=await fetch(path,body?{method:'POST',headers:{'Content-Type':'application/json','X-Paper-Workbench':'1'},body:JSON.stringify(body)}:{});const d=await r.json();if(!r.ok)throw new Error(d.error.message);return d;},{path,body});
  async function openFacet(selector){const detail=page.locator('#facets details').filter({has:page.locator(selector)});if(await detail.getAttribute('open')===null)await detail.locator('summary').click();}
  async function create(title,author,year,journal,tags){
    await page.locator('#new-item').click();
    await page.locator('[data-field=title]').fill(stamp+' '+title);
    while(await page.locator('[data-action=remove-author]').count())await page.locator('[data-action=remove-author]').first().click();
    await page.getByRole('button',{name:'＋ 添加作者'}).click();
    await page.getByRole('textbox',{name:'作者 1 姓名',exact:true}).fill(author);
    await page.locator('[data-field=year]').fill(String(year));
    await page.locator('[data-field=journal]').fill(journal);
    await page.locator('[data-field=tags]').fill(tags);
    await page.getByRole('button',{name:'保存信息',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('.metadata-form'));
    const r=await request('/api/library/search',{query:{text:stamp+' '+title}});
    const exact=r.items.filter(item=>item.title===stamp+' '+title);
    check('create '+title,exact.length===1,{matches:r.total,exact:exact.length});return exact[0];
  }
  const a=await create('Nb₅Si₃ 密度 A','张三',2024,'Phys. Rev. B','密度；金属');
  const b=await create('密度 B','李四',2025,'Physical Review B','密度');
  await create('不匹配样本','王五',2022,'Other Journal','其他');
  await page.locator('#search').fill(stamp);await page.locator('#search').press('Enter');
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===3);
  await openFacet('[data-facet-search=authors]');
  await page.locator('[data-dimension=authors][value="张三"]').check();
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===1);
  await page.locator('[data-dimension=authors][value="李四"]').check();
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  check('OR within author selection',true);
  await openFacet('[data-year=from]');
  await page.locator('[data-year=from]').fill('2024');await page.locator('[data-year=from]').press('Tab');
  await page.waitForFunction(()=>document.querySelector('[data-year=from]')?.value==='2024');
  await page.locator('[data-year=to]').fill('2024');await page.locator('[data-year=to]').press('Tab');
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===1);
  check('author AND year interval',await page.locator('#table-body tr').first().getAttribute('data-id')===a.id);
  await page.locator('#journal-aliases').click();
  await page.locator('dialog [name=alias]').fill('Phys. Rev. B');await page.locator('dialog [name=canonical]').fill('Physical Review B');
  await page.getByRole('button',{name:'添加归一规则'}).click();
  await page.waitForFunction(()=>document.querySelector('#alias-list')?.textContent.includes('Phys. Rev. B'));
  await page.getByRole('button',{name:'关闭对话框'}).click();
  await page.locator('[data-year=to]').fill('2025');await page.locator('[data-year=to]').press('Tab');
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  await openFacet('[data-facet-search=journals]');
  await page.locator('[data-dimension=journals][value="physical review b"]').check();
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  await openFacet('[data-facet-search=tags]');
  await page.locator('[data-dimension=tags][value="密度"]').check();await page.locator('[data-dimension=tags][value="金属"]').check();
  await page.locator('[data-query-field=tagMatch]').selectOption('all');
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===1);
  check('AND across author/year/journal/tags',await page.locator('#table-body tr').first().getAttribute('data-id')===a.id);
  await page.locator('#save-query').click();await page.locator('dialog [name=name]').fill(stamp+' 智能集合');
  await page.locator('dialog button[type=submit]').click();await page.waitForFunction(()=>!document.querySelector('dialog'));
  const d=await create('密度 D','张三',2025,'Physical Review B','密度；金属');
  await page.reload();await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  const titles=await page.locator('#table-body .paper-title').allTextContents();check('saved query persists and includes newly matching item',titles.some(x=>x.includes('Nb₅Si₃'))&&titles.some(x=>x.includes('密度 D')),titles);
  await page.locator('#select-all').check();await page.locator('#batch-edit').click();
  await page.locator('dialog [name=readingStatus]').selectOption('read');await page.locator('dialog [name=addTags]').fill('已筛选');
  await page.locator('dialog button[type=submit]').click();await page.waitForFunction(()=>!document.querySelector('dialog'));
  const afterA=await request('/api/library/items/'+a.id),afterD=await request('/api/library/items/'+d.id);
  check('batch reading status and tags',afterA.metadata.readingStatus==='read'&&afterD.metadata.tags.includes('已筛选'));
  const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export-selected').click()]);
  await download.saveAs('output/stage2-csl-export.json');check('CSL export download',download.suggestedFilename()==='references.json');
  await page.locator('#trash-selected').click();await page.locator('dialog button[type=submit]').click();
  await page.waitForFunction(()=>!document.querySelector('dialog')&&document.querySelectorAll('#table-body tr').length===0);
  await page.locator('[data-view=trash]').click();await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  await page.locator('#select-all').check();await page.locator('#trash-selected').click();await page.locator('dialog button[type=submit]').click();
  await page.waitForFunction(()=>!document.querySelector('dialog')&&document.querySelectorAll('#table-body tr').length===0);
  await page.locator('.saved-link').filter({hasText:stamp+' 智能集合'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('#table-body tr').length===2);
  check('trash and restore preserve query membership',true);
  const restored=await request('/api/library/items/'+a.id);check('scientific title retained',restored.metadata.title.includes('Nb₅Si₃'),restored.metadata.title);
  await page.locator('[data-select="'+a.id+'"]').click();
  await page.screenshot({path:'output/playwright/stage2-combined-search.png'});
  return {stamp,checks,itemIds:[a.id,b.id,d.id],savedSearch:(await request('/api/library/searches')).find(x=>x.name===stamp+' 智能集合')};
}
