#!/usr/bin/env node
/**
 * Boot one isolated verification instance of the Harness Web profile with the
 * Paper Workbench plugin patch overlay. No profile package is installed and the
 * user's Desktop profile is untouched: the bundle row is inserted by the
 * documented `--patch` development overlay.
 *
 * The instance writes its own log and uses its own verification data directory,
 * so it never touches data/workspace and parallel runs do not fight over the
 * single-library lock.
 */
import { spawn } from 'node:child_process'
import { existsSync, mkdirSync, openSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath } from 'node:url'

const toolsDir = path.dirname(fileURLToPath(import.meta.url))
const pluginRoot = path.resolve(toolsDir, '..')
const repoRoot = path.resolve(pluginRoot, '..', '..')
const qaDir = path.join(pluginRoot, 'qa')
mkdirSync(qaDir, { recursive: true })

const harnessRoot = process.env.DSH_PAPER_WORKBENCH_HARNESS
if (!harnessRoot) throw new Error('Set DSH_PAPER_WORKBENCH_HARNESS to the directory containing DeepSeek Harness.exe')
const exe = path.join(harnessRoot, 'DeepSeek Harness.exe')
const cli = path.join(harnessRoot, 'resources', 'app.asar', 'dsh', 'node_modules', '@deepseek-ai', 'dsh-desktop-host', 'lib', 'cli.js')
const profile = process.env.DSH_PAPER_WORKBENCH_PROFILE || 'web'
if (!existsSync(exe)) throw new Error(`Harness executable not found: ${exe}`)

const args = {}
for (let i = 2; i < process.argv.length; i += 1) {
  const token = process.argv[i]
  if (!token.startsWith('--')) continue
  const value = process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : 'true'
  args[token.slice(2)] = value
  if (value !== 'true') i += 1
}

const port = Number(args.port || 43200 + Math.floor(Math.random() * 300))
const runId = `${Date.now().toString(36)}-${port}`
const bundleDir = args.bundle ? path.resolve(args.bundle) : null
if (bundleDir && !existsSync(path.join(bundleDir, 'index.js'))) {
  throw new Error(`--bundle ${bundleDir} does not contain index.js`)
}
const dataRoot = args['data-root']
  || (bundleDir ? path.join(tmpdir(), `dsh-paper-workbench-data-${runId}`) : `data/harness-qa/run-${runId}`)
const outLog = path.join(qaDir, `web-${port}.out.log`)
const errLog = path.join(qaDir, `web-${port}.err.log`)
const patchFile = bundleDir
  ? path.join(bundleDir, `qa-run-${port}.patch.yml`)
  : path.join(qaDir, `dev-${port}.patch.yml`)
// `--unlock-llm` adds a throwaway DeepSeek API-key provider row so an isolated
// profile without account credentials can still resolve the default model and
// enable the native composer. The key is deliberately invalid: real requests
// fail with an authentication error, but the prompt admission/pre-step path is
// exercised end to end. No real model call or personal content is involved.
const unlockLlm = args['unlock-llm'] === 'true'
const rows = [
  '# Generated by tools/run-isolated.mjs for one isolated verification run.',
  readFileSync(path.join(bundleDir || pluginRoot, 'cordis.patch.yml'), 'utf8')
    .replace('name: dsh-paper-workbench', `name: ${bundleDir ? './index.js' : '../index.js'}`).trimEnd(),
  '      config:',
  `        dataRoot: ${JSON.stringify(dataRoot)}`,
  ...(args['no-auto-read']==='true'?['        autoRead: false']:[]),
]
if (unlockLlm) {
  rows.push(
    '    - id: qa-llm-deepseek-api-key',
    "      name: '@deepseek-ai/dsh-llm-deepseek-api-key'",
    '      config:',
    '        apiKeyEnv: DEEPSEEK_API_KEY',
  )
}
rows.push('')
writeFileSync(patchFile, rows.join('\n'))

const env = {
  ...process.env,
  ELECTRON_RUN_AS_NODE: '1',
  ...(unlockLlm ? { DEEPSEEK_API_KEY: process.env.DEEPSEEK_API_KEY || 'sk-isolated-qa-invalid' } : {}),
}
const stdout = openSync(outLog, 'w')
const stderr = openSync(errLog, 'w')
const child = spawn(
  exe,
  [
    '--expose-internals',
    cli,
    '--profile',
    profile,
    '--patch',
    patchFile,
    '--no-open',
    '--port',
    String(port),
  ],
  {
    cwd: repoRoot,
    env,
    detached: true,
    windowsHide: true,
    stdio: ['ignore', stdout, stderr],
  },
)
child.unref()

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))
async function waitForUrl(timeoutMs) {
  const deadline = Date.now() + timeoutMs
  while (Date.now() < deadline) {
    try {
      const text = readFileSync(outLog, 'utf8')
      const lines = text
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line.startsWith('dsh web: '))
      if (lines.length > 0) return lines[lines.length - 1].slice('dsh web: '.length)
    } catch {
      /* log not written yet */
    }
    await sleep(250)
  }
  throw new Error(`Timed out waiting for the isolated Web URL. Log: ${outLog}`
    + `\n${readFileSync(errLog, 'utf8').slice(-4000)}`)
}

const url = await waitForUrl(180000)
writeFileSync(
  path.join(qaDir, 'last-run.json'),
  JSON.stringify({ url: url.replace(/([?&]token=)[^&\s"'`]+/gu, '$1<redacted>'), hostPid: child.pid, port, dataRoot, outLog, errLog, startedAt: new Date().toISOString() }, null, 2),
)
console.log(JSON.stringify({ url, hostPid: child.pid, port, dataRoot, outLog, errLog }))

